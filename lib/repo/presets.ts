export function findRepoPreset(url: string): RepoIntelligenceReport | null {
  const clean = url.trim().replace(/\/+$/, '').toLowerCase();
  for (const [key, report] of Object.entries(REPO_PRESETS)) {
    if (key.replace(/\/+$/, '').toLowerCase() === clean) {
      return report;
    }
  }
  return null;
}
